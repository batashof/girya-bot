-- Режим тренировок и тренировка по теме (ADR-016).
--
-- daily — как было: программа дня, утреннее напоминание и вечерний пинг.
-- on_demand — напоминаний о программе нет: тренировка начинается по запросу, программой
-- дня или темой. Программа дня и её лестницы при этом никуда не деваются.
ALTER TABLE users ADD COLUMN training_mode TEXT NOT NULL DEFAULT 'daily'; -- daily | on_demand

-- Тема — это шаблон с kind = 'theme' без пунктов: к нему привязываются сессии по теме,
-- а состав берётся из справочника по группе. group_code — какую группу exercises тема
-- собирает; у дней и микро-блоков он пустой.
ALTER TABLE templates ADD COLUMN group_code TEXT;
